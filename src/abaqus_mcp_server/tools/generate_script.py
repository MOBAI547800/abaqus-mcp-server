def _generate_cantilever(name: str, p: dict) -> str:
    L = p.get("length", 100)
    W = p.get("width", 10)
    H = p.get("height", 10)
    F = p.get("force", 1000)
    E = p.get("youngs_modulus", 210000)
    nu = p.get("poissons_ratio", 0.3)
    mesh_size = p.get("mesh_size", 5)

    return f'''"""Cantilever beam static analysis — generated by Abaqus MCP Server."""

from abaqus import *
from abaqusConstants import *

# Create model
Mdb()
model = mdb.Model(name="{name}")
if "Model-1" in mdb.models:
    del mdb.models["Model-1"]

# Create part
s = model.ConstrainedSketch(name="beam_profile", sheetSize=200.0)
s.rectangle(point1=(0.0, 0.0), point2=({L}, {H}))
beam = model.Part(name="Beam", dimensionality=THREE_D, type=DEFORMABLE_BODY)
beam.BaseSolidExtrude(sketch=s, depth={W})

# Material
mat = model.Material(name="Steel")
mat.Elastic(table=(({E}, {nu}),))

# Section
model.HomogeneousSolidSection(name="BeamSection", material="Steel")
region = beam.Set(cells=beam.cells.findAt(((0, 0, 0),)), name="AllCells")
beam.SectionAssignment(region=region, sectionName="BeamSection")

# Assembly
ass = model.rootAssembly
inst = ass.Instance(name="Beam-1", part=beam, dependent=ON)

# Step
model.StaticStep(name="Step-1", previous="Initial", nlgeom=OFF,
    initialInc=0.1, maxInc=0.1, minInc=1e-05)

# Boundary condition — fixed end
fixed_faces = inst.faces.findAt(((0, {H/2}, {W/2}),))
fixed_region = inst.Set(faces=fixed_faces, name="FixedEnd")
model.EncastreBC(name="FixedEnd", createStepName="Initial", region=fixed_region)

# Load — point force at free end
load_face = inst.faces.findAt((({L}, {H/2}, {W/2}),))
load_region = inst.Set(faces=load_face, name="LoadedEnd")
model.Pressure(name="TipLoad", createStepName="Step-1",
    region=load_region, magnitude={F/(W*H)})

# Mesh
elem_type = mesh.ElemType(elemCode=C3D8R)
beam.setElementType(regions=(beam.cells,), elemTypes=(elem_type,))
beam.seedPart(size={mesh_size})
beam.generateMesh()

# Job
job = mdb.Job(name="{name}", model="{name}")
job.writeInput()
print("Job {name} input file written.")
'''


def _generate_static(name: str, p: dict) -> str:
    return _generate_cantilever(name, p)  # Alias for now


