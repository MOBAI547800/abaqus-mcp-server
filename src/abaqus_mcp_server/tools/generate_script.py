"""Generate ready-to-run Abaqus Python scripts from descriptions."""

from __future__ import annotations

import logging
from pathlib import Path

from abaqus_mcp_server.app import mcp
from abaqus_mcp_server.config import AbaqusServerConfig
from abaqus_mcp_server.security import validate_filename, validate_path

logger = logging.getLogger(__name__)


@mcp.tool(
    name="generate_script",
    description="Generate an Abaqus Python script for common modeling tasks. "
    "Returns a ready-to-run Python script that can be saved and executed "
    "via the run_script tool. Supports: static_analysis, modal_analysis, "
    "contact_analysis, and cantilever_beam.",
)
async def generate_script(
    task: str,
    model_name: str,
    output_script: str,
    parameters: str = "{}",
) -> str:
    """Generate an Abaqus Python modeling script.

    Args:
        task: Type of analysis (static_analysis, modal_analysis, contact_analysis, cantilever_beam).
        model_name: Name for the Abaqus model.
        output_script: Path to write the generated script (relative to workspace).
        parameters: JSON dict of model parameters (e.g., length, width, height, force).
    """
    import json as _json

    cfg = AbaqusServerConfig()
    ws = cfg.resolve_workspace()

    try:
        params = _json.loads(parameters)
    except _json.JSONDecodeError as exc:
        return f"Error: Invalid JSON parameters: {exc}"

    # Validate output path
    try:
        output = validate_path(output_script, workspace=ws)
    except Exception as exc:
        return f"Error: Invalid output path: {exc}"

    if output.suffix.lower() not in (".py",):
        return "Error: output_script must have a .py extension."

    # Generate based on task type
    gen_fns = {
        "cantilever_beam": _generate_cantilever,
        "static_analysis": _generate_static,
        "modal_analysis": _generate_modal,
        "contact_analysis": _generate_contact,
    }

    if task not in gen_fns:
        return f"Error: Unknown task '{task}'. Available: {', '.join(gen_fns.keys())}"

    script = gen_fns[task](model_name, params)

    # Write the script
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(script, encoding="utf-8")

    lines = [
        f"=== Script Generated ===",
        f"Task: {task}",
        f"Model: {model_name}",
        f"Saved to: {output}",
        f"",
        f"To run this script: run_script(script_path='{output_script}')",
        f"",
        f"--- Script preview (first 50 lines) ---",
    ]
    preview = script.splitlines()[:50]
    lines.extend(preview)

    return "\n".join(lines)


