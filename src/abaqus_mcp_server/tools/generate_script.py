def _generate_contact(name: str, p: dict) -> str:
    return f'''"""Contact analysis template — generated by Abaqus MCP Server.

This is a template; modify geometry, materials, and contact properties
to match your specific model.
"""
from abaqus import *
from abaqusConstants import *

Mdb()
model = mdb.Model(name="{name}")
if "Model-1" in mdb.models:
    del mdb.models["Model-1"]

# Create two parts in contact
# Part 1: Base
s1 = model.ConstrainedSketch(name="base_sketch", sheetSize=200.0)
s1.rectangle(point1=(0.0, 0.0), point2=(100, 20))
base = model.Part(name="Base", dimensionality=THREE_D, type=DEFORMABLE_BODY)
base.BaseSolidExtrude(sketch=s1, depth=100)

# Part 2: Punch
s2 = model.ConstrainedSketch(name="punch_sketch", sheetSize=200.0)
s2.rectangle(point1=(40, 20), point2=(60, 40))
punch = model.Part(name="Punch", dimensionality=THREE_D, type=DEFORMABLE_BODY)
punch.BaseSolidExtrude(sketch=s2, depth=100)

# Materials
steel = model.Material(name="Steel")
steel.Elastic(table=((210000, 0.3),))
model.HomogeneousSolidSection(name="SolidSection", material="Steel")

for part_name in ["Base", "Punch"]:
    p = model.parts[part_name]
    p.SectionAssignment(
        region=p.Set(cells=p.cells.findAt(((0, 0, 0),)), name="All"),
        sectionName="SolidSection")

# Assembly
ass = model.rootAssembly
base_inst = ass.Instance(name="Base-1", part=base, dependent=ON)
punch_inst = ass.Instance(name="Punch-1", part=punch, dependent=ON)

# Contact pair
model.SurfaceToSurfaceContactExp(name="Contact",
    master=base_inst.faces.findAt(((50, 20, 50),)),
    slave=punch_inst.faces.findAt(((50, 20, 50),)),
    sliding=FINITE)
model.interactions["Contact"].includedStepPairs = (("Step-1",),)

# Step
model.StaticStep(name="Step-1", previous="Initial",
    initialInc=0.01, maxInc=0.1, minInc=1e-08)

# BCs: fix base bottom, push punch down
base_bot = base_inst.Set(
    faces=base_inst.faces.findAt(((50, 0, 50),)), name="BaseBottom")
model.DisplacementBC(name="FixBase", createStepName="Initial",
    region=base_bot, u1=0.0, u2=0.0, u3=0.0)

punch_top = punch_inst.Set(
    faces=punch_inst.faces.findAt(((50, 40, 50),)), name="PunchTop")
model.DisplacementBC(name="PushDown", createStepName="Step-1",
    region=punch_top, u2=-5.0)

# Mesh
for part in [base, punch]:
    elem_type = mesh.ElemType(elemCode=C3D8R)
    part.setElementType(regions=(part.cells,), elemTypes=(elem_type,))
    part.seedPart(size=5)
    part.generateMesh()

job = mdb.Job(name="{name}", model="{name}")
job.writeInput()
print("Job {name} input file written.")
'''
